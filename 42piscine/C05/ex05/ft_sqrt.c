int	ft_sqrt(int nb)
{
	long	num;

	num = 1;
	if (nb < 0)
		return (0);
	if (nb == 1)
		return (1);
	while (nb >= num * num)
	{
		if (nb == (num * num))
			return (num);
		num++;
	}
	return (0);
}
