#include "ft_printf.h"

void	ft_d(long nb)
{
	if (nb < 0)
	{
		write(1, "-", 1);
		nb = nb * -1;
	}
	if (nb >= 10)
		ft_d(nb / 10);
	ft_putchar(nb % 10);
}
